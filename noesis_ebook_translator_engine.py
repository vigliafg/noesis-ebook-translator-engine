class Base:
    name: str | None = None
    alias: str | None = None
    free: bool = False

    lang_codes: dict[str, Any] = {}
    config: dict[str, Any] = {}
    endpoint: str | None = None
    method: str = 'POST'
    headers: dict[str, str] = {}
