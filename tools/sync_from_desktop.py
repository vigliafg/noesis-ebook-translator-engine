class Dispatcher:
    def __init__(self, callback, *args, **kwargs):
        self.callback = callback
        self.args = args
        self.kwargs = kwargs

    def __call__(self, *args, **kwargs):
        if self.callback is None:
            return None
        merged = dict(self.kwargs)
        merged.update(kwargs)
        return self.callback(*(self.args + args), **merged)


