BANNER = (
    "\n\n# " + "─" * 78 + "\n"
    "#  {path}\n"
    "# " + "─" * 78 + "\n\n"
)


def _strip_imports(source: str) -> str:
    """Remove ``calibre`` and relative imports (handles parenthesised imports)."""
    lines = source.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if _DROP_IMPORT.match(line.strip()):
            depth = line.count("(") - line.count(")")
            while depth > 0 and i + 1 < len(lines):
                i += 1
                depth += lines[i].count("(") - lines[i].count(")")
            i += 1
            continue
        out.append(line)
        i += 1
    return "\n".join(out)


def build_text(desktop: Path) -> str:
    parts = [HEADER]
    for module in CORE_MODULES:
        src = desktop / PACKAGE / module
        if not src.is_file():
            raise SystemExit(f"missing desktop module: {src}")
        parts.append(BANNER.format(path=module))
        parts.append(_strip_imports(src.read_text(encoding="utf-8")).strip("\n"))
    frontend = ROOT / "tools" / "frontend.py"
    if not frontend.is_file():
        raise SystemExit(f"missing frontend: {frontend}")
    parts.append("\n\n")
    parts.append(frontend.read_text(encoding="utf-8").strip("\n"))
    parts.append("\n")
    return "\n".join(parts)


def _desktop_commit(desktop: Path) -> str:
    try:
        out = subprocess.run(
            ["git", "-C", str(desktop), "rev-parse", "HEAD"],
            capture_output=True, text=True, check=True, timeout=10)
        return out.stdout.strip()
    except Exception:  # noqa: BLE001 - best effort
        return ""


def copy_fixtures(desktop: Path) -> int:
    """Copy the shared test corpus from the desktop repo (best effort)."""
    copied = 0
    for rel in FIXTURE_DIRS:
        src = desktop / rel
        if not src.is_dir():
            continue
        dst = ROOT / rel
        dst.mkdir(parents=True, exist_ok=True)
        for item in sorted(src.rglob("*")):
            if item.is_dir():
                continue
            target = dst / item.relative_to(src)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item, target)
            copied += 1
    return copied


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--desktop", type=Path, default=DEFAULT_DESKTOP,
                    help="path to the desktop repository checkout")
    args = ap.parse_args(argv)
    desktop: Path = args.desktop.resolve()
    if not (desktop / PACKAGE).is_dir():
        raise SystemExit(f"desktop package not found under {desktop}")

    text = build_text(desktop)
    OUTPUT.write_text(text, encoding="utf-8")

    fixtures = copy_fixtures(desktop)

    meta = {
        "desktop_repo": str(desktop),
        "desktop_commit": _desktop_commit(desktop),
        "synced_at": _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
        "verbatim": VERBATIM,
        "overrides": OVERRIDES,
        "frontend": "tools/frontend.py",
        "fixtures": FIXTURE_DIRS,
    }
    (ROOT / "ENGINE_SOURCE.json").write_text(
        json.dumps(meta, indent=2) + "\n", encoding="utf-8")

    print(f"wrote {OUTPUT.name}: {len(text.splitlines())} lines, "
          f"{len(CORE_MODULES)} modules + frontend")
    print(f"copied {fixtures} fixture files from {FIXTURE_DIRS}")
    print(f"desktop commit: {meta['desktop_commit'] or '(unknown)'}")
    return 0


